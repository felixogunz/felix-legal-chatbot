import sqlite3

import psycopg
from psycopg.rows import dict_row

from config import Config


def using_postgres():
    """Check whether PostgreSQL is configured."""
    return bool(Config.DATABASE_URL)


def get_connection():
    """Connect to PostgreSQL or the local SQLite database."""

    if using_postgres():
        return psycopg.connect(
            Config.DATABASE_URL,
            row_factory=dict_row,
        )

    connection = sqlite3.connect(Config.DATABASE_PATH)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")

    return connection


def execute_query(connection, query, parameters=()):
    """Use the correct parameter placeholders for each database."""

    if using_postgres():
        query = query.replace("?", "%s")

    return connection.execute(query, parameters)


def init_db():
    """Create the conversation and message tables."""

    connection = get_connection()

    try:
        if using_postgres():
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS conversations (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL DEFAULT 'New Legal Research',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """
            )

            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    conversation_id BIGINT NOT NULL,
                    role TEXT NOT NULL
                        CHECK (role IN ('user', 'assistant')),
                    content TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (conversation_id)
                        REFERENCES conversations(id)
                        ON DELETE CASCADE
                )
                """
            )

            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_messages_conversation
                ON messages(conversation_id, id)
                """
            )

        else:
            connection.executescript(
                """
                CREATE TABLE IF NOT EXISTS conversations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    title TEXT NOT NULL DEFAULT 'New Legal Research',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                );

                CREATE TABLE IF NOT EXISTS messages (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    conversation_id INTEGER NOT NULL,
                    role TEXT NOT NULL
                        CHECK (role IN ('user', 'assistant')),
                    content TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (conversation_id)
                        REFERENCES conversations(id)
                        ON DELETE CASCADE
                );

                CREATE INDEX IF NOT EXISTS idx_messages_conversation
                ON messages(conversation_id, id);
                """
            )

        connection.commit()

    finally:
        connection.close()


def create_conversation(title="New Legal Research"):
    """Create a conversation and return its ID."""

    connection = get_connection()

    try:
        if using_postgres():
            cursor = execute_query(
                connection,
                """
                INSERT INTO conversations (title)
                VALUES (?)
                RETURNING id
                """,
                (title,),
            )

            conversation_id = cursor.fetchone()["id"]

        else:
            cursor = execute_query(
                connection,
                """
                INSERT INTO conversations (title)
                VALUES (?)
                """,
                (title,),
            )

            conversation_id = cursor.lastrowid

        connection.commit()
        return conversation_id

    finally:
        connection.close()


def save_message(conversation_id, role, content):
    """Save a user or assistant message."""

    if role not in ("user", "assistant"):
        raise ValueError("Invalid message role.")

    connection = get_connection()

    try:
        execute_query(
            connection,
            """
            INSERT INTO messages (
                conversation_id,
                role,
                content
            )
            VALUES (?, ?, ?)
            """,
            (conversation_id, role, content),
        )

        execute_query(
            connection,
            """
            UPDATE conversations
            SET updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
            """,
            (conversation_id,),
        )

        connection.commit()

    finally:
        connection.close()


def get_messages(conversation_id):
    """Retrieve messages in their original order."""

    connection = get_connection()

    try:
        rows = execute_query(
            connection,
            """
            SELECT role, content, created_at
            FROM messages
            WHERE conversation_id = ?
            ORDER BY id ASC
            """,
            (conversation_id,),
        ).fetchall()

        return [dict(row) for row in rows]

    finally:
        connection.close()


def get_conversations(limit=50):
    """Retrieve recent conversations, newest activity first."""

    connection = get_connection()

    try:
        rows = execute_query(
            connection,
            """
            SELECT
                c.id,
                c.title,
                c.created_at,
                c.updated_at,
                (
                    SELECT content
                    FROM messages
                    WHERE conversation_id = c.id
                      AND role = 'user'
                    ORDER BY id ASC
                    LIMIT 1
                ) AS first_message
            FROM conversations AS c
            ORDER BY c.updated_at DESC, c.id DESC
            LIMIT ?
            """,
            (limit,),
        ).fetchall()

        return [dict(row) for row in rows]

    finally:
        connection.close()


def get_conversation(conversation_id):
    """Retrieve one conversation by its ID."""

    connection = get_connection()

    try:
        row = execute_query(
            connection,
            """
            SELECT id, title, created_at, updated_at
            FROM conversations
            WHERE id = ?
            """,
            (conversation_id,),
        ).fetchone()

        return dict(row) if row else None

    finally:
        connection.close()


def rename_conversation(conversation_id, new_title):
    """Rename an existing conversation."""

    title = new_title.strip()

    if not title:
        raise ValueError("The conversation title cannot be empty.")

    if len(title) > 150:
        raise ValueError(
            "The conversation title cannot exceed 150 characters."
        )

    connection = get_connection()

    try:
        cursor = execute_query(
            connection,
            """
            UPDATE conversations
            SET title = ?, updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
            """,
            (title, conversation_id),
        )

        connection.commit()

        return cursor.rowcount > 0

    finally:
        connection.close()


def delete_conversation(conversation_id):
    """Delete a conversation and its associated messages."""

    connection = get_connection()

    try:
        cursor = execute_query(
            connection,
            """
            DELETE FROM conversations
            WHERE id = ?
            """,
            (conversation_id,),
        )

        connection.commit()

        return cursor.rowcount > 0

    finally:
        connection.close()
